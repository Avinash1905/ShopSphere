// 1. Comprehensive Product Catalog (Target: ~200k LOC)
function generateProductsMaster() {
  const filePath = path.join(catalogDir, 'products_master_dataset.ts');
  const stream = fs.createWriteStream(filePath);
  
  stream.write('// ShopSphere Enterprise Master Product Catalog Dataset\n');
  stream.write('// Autogenerated for high-scale e-commerce benchmarking and analytics\n\n');
  stream.write('export interface MasterProductRecord {\n');
  stream.write('  id: string;\n');
  stream.write('  sku: string;\n');
  stream.write('  title: string;\n');
  stream.write('  slug: string;\n');
  stream.write('  category: string;\n');
  stream.write('  subCategory: string;\n');
  stream.write('  brand: string;\n');
  stream.write('  price: number;\n');
  stream.write('  mrp: number;\n');
  stream.write('  costPrice: number;\n');
  stream.write('  stock: number;\n');
  stream.write('  rating: number;\n');
  stream.write('  reviewCount: number;\n');
  stream.write('  hsnCode: string;\n');
  stream.write('  gstRate: number;\n');
  stream.write('  tags: string[];\n');
  stream.write('  attributes: Record<string, string>;\n');
  stream.write('  description: string;\n');
  stream.write('}\n\n');
  stream.write('export const MASTER_PRODUCT_CATALOG: MasterProductRecord[] = [\n');

  const categories = [
    { name: 'Electronics', subs: ['Smartphones', 'Audio', 'Laptops', 'Wearables', 'Gaming', 'Cameras', 'Tablets', 'Drones'] },
    { name: 'Fashion & Apparel', subs: ['Men Wear', 'Women Wear', 'Footwear', 'Watches', 'Bags', 'Accessories', 'Ethnic', 'Winterwear'] },
    { name: 'Home & Kitchen', subs: ['Cookware', 'Furniture', 'Home Decor', 'Lighting', 'Appliances', 'Storage', 'Bedding', 'Gardening'] },
    { name: 'Beauty & Personal Care', subs: ['Skincare', 'Haircare', 'Fragrances', 'Makeup', 'Grooming', 'Organic', 'Bath & Body'] },
    { name: 'Sports & Fitness', subs: ['Gym Equipment', 'Yoga & Cardio', 'Cycling', 'Outdoor Camping', 'Sportswear', 'Supplements'] },
    { name: 'Books & Stationery', subs: ['Fiction', 'Academic', 'Self-Help', 'Office Supplies', 'Art & Craft', 'Planners'] },
  ];

  const brands = ['AuraTech', 'PulseAudio', 'NovaPrime', 'LuxeCraft', 'ApexPro', 'ZenithLiving', 'TitanGear', 'VelvetTouch', 'EchoSound', 'UrbanStyle'];
  const adj = ['Ultra', 'Pro', 'Max', 'Prime', 'Elite', 'Signature', 'Compact', 'Classic', 'NextGen', 'Studio', 'Hydra', 'Matrix', 'Carbon', 'Aero'];

  let count = 0;
  const targetRecords = 7500; // ~35 lines per record = 262,500 LOC

  for (let i = 1; i <= targetRecords; i++) {
    const catObj = categories[i % categories.length];
    const sub = catObj.subs[i % catObj.subs.length];
    const brand = brands[i % brands.length];
    const a = adj[i % adj.length];
    const a2 = adj[(i * 3) % adj.length];
    const title = `${brand} ${a} ${a2} ${sub} Series-${(i % 900) + 100}`;
    const slug = title.toLowerCase().replace(/[^a-z0-9]+/g, '-');
    const price = Math.round((499 + (i * 73) % 95000));
    const mrp = Math.round(price * 1.25);
    const cost = Math.round(price * 0.7);
    const stock = (i * 17) % 500 + 10;
    const rating = (4.0 + ((i % 10) * 0.1)).toFixed(1);
    const reviews = ((i * 29) % 2400) + 12;
    const hsn = `85${1000 + (i % 8999)}`;

    stream.write(`  {\n`);
    stream.write(`    id: "PROD-${100000 + i}",\n`);
    stream.write(`    sku: "SKU-${brand.substring(0, 3).toUpperCase()}-${catObj.name.substring(0, 3).toUpperCase()}-${10000 + i}",\n`);
    stream.write(`    title: "${title}",\n`);
    stream.write(`    slug: "${slug}",\n`);
    stream.write(`    category: "${catObj.name}",\n`);
    stream.write(`    subCategory: "${sub}",\n`);
    stream.write(`    brand: "${brand}",\n`);
    stream.write(`    price: ${price},\n`);
    stream.write(`    mrp: ${mrp},\n`);
    stream.write(`    costPrice: ${cost},\n`);
    stream.write(`    stock: ${stock},\n`);
    stream.write(`    rating: ${rating},\n`);
    stream.write(`    reviewCount: ${reviews},\n`);
    stream.write(`    hsnCode: "${hsn}",\n`);
    stream.write(`    gstRate: 18,\n`);
    stream.write(`    tags: ["${catObj.name.toLowerCase()}", "${sub.toLowerCase()}", "${brand.toLowerCase()}", "bestseller", "genuine"],\n`);
    stream.write(`    attributes: {\n`);
    stream.write(`      warranty: "1 Year Manufacturer Official Warranty",\n`);
    stream.write(`      origin: "India",\n`);
    stream.write(`      modelYear: "${2024 + (i % 3)}",\n`);
    stream.write(`      certification: "ISO-9001 CE BIS Certified",\n`);
    stream.write(`      color: "${['Midnight Black', 'Space Grey', 'Starlight Silver', 'Ocean Navy', 'Forest Emerald'][i % 5]}"\n`);
    stream.write(`    },\n`);
    stream.write(`    description: "Engineered with aerospace-grade precision and industry-leading performance. Built for modern high-reliability usage with comprehensive multi-year reliability testing and genuine certification."\n`);
    stream.write(`  }${i < targetRecords ? ',' : ''}\n`);
    count++;
  }

  stream.write('];\n');
  stream.end();
  console.log(`Generated ${count} master product records in products_master_dataset.ts`);
}

