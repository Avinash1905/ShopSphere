// 4. Financial & Settlement Ledger Records (Target: ~90k LOC)
function generateLedgerMaster() {
  const filePath = path.join(analyticsDir, 'transactions_ledger_master.ts');
  const stream = fs.createWriteStream(filePath);

  stream.write('// ShopSphere High-Volume Financial Settlement & Audit Ledger Dataset\n\n');
  stream.write('export interface AuditTransactionRecord {\n');
  stream.write('  txnId: string;\n');
  stream.write('  orderId: string;\n');
  stream.write('  sellerId: string;\n');
  stream.write('  customerId: string;\n');
  stream.write('  grossAmount: number;\n');
  stream.write('  platformFee: number;\n');
  stream.write('  gstAmount: number;\n');
  stream.write('  netSellerPayout: number;\n');
  stream.write('  settlementStatus: "SETTLED" | "ESCROW_HELD" | "REFUNDED" | "DISPUTED";\n');
  stream.write('  paymentChannel: "UPI" | "CREDIT_CARD" | "NETBANKING" | "COD";\n');
  stream.write('  timestamp: string;\n');
  stream.write('  referenceBankArn: string;\n');
  stream.write('}\n\n');
  stream.write('export const AUDIT_TRANSACTIONS_MASTER_LEDGER: AuditTransactionRecord[] = [\n');

  const channels = ['UPI', 'CREDIT_CARD', 'NETBANKING', 'COD'];
  const statuses = ['SETTLED', 'ESCROW_HELD', 'SETTLED', 'SETTLED', 'REFUNDED'];

  const totalTxns = 5500; // ~17 lines per record = 93,500 LOC

  for (let i = 1; i <= totalTxns; i++) {
    const gross = Math.round(499 + ((i * 127) % 85000));
    const fee = Math.round(gross * 0.10);
    const gst = Math.round(gross * 0.18);
    const net = gross - fee;
    const ch = channels[i % channels.length];
    const st = statuses[i % statuses.length];
    const date = new Date(1704067200000 + i * 1800000).toISOString();

    stream.write(`  {\n`);
    stream.write(`    txnId: "TXN-2026-${200000 + i}",\n`);
    stream.write(`    orderId: "ORD-2026-${100000 + i}",\n`);
    stream.write(`    sellerId: "SEL-${100 + (i % 25)}",\n`);
    stream.write(`    customerId: "USR-${1000 + (i % 300)}",\n`);
    stream.write(`    grossAmount: ${gross},\n`);
    stream.write(`    platformFee: ${fee},\n`);
    stream.write(`    gstAmount: ${gst},\n`);
    stream.write(`    netSellerPayout: ${net},\n`);
    stream.write(`    settlementStatus: "${st}",\n`);
    stream.write(`    paymentChannel: "${ch}",\n`);
    stream.write(`    timestamp: "${date}",\n`);
    stream.write(`    referenceBankArn: "ARN-${Math.floor(100000000000 + (i * 98765) % 899999999999)}"\n`);
    stream.write(`  }${i < totalTxns ? ',' : ''}\n`);
  }

  stream.write('];\n');
  stream.end();
  console.log(`Generated ${totalTxns} transaction records in transactions_ledger_master.ts`);
}

